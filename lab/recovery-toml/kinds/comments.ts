// Comments as other notations write them, and comments that lost their #.
import {type Edit, insertAt, removeRange, replaceOneForOne} from '../edits.ts'
import type {Random} from '../random.ts'
import {runTableParser} from '../table-parser.ts'
import {chooseForm} from './assignment.ts'
import {type Comment, type Scan, indentationAt, lastOnLine, lineAt} from './scan.ts'
import type {Damage, KindDefinition} from './types.ts'

const styles = [['//', 45], [';', 22], ['--', 13], ['/* */', 12], ['<!-- -->', 8]] as const
type CommentStyle = typeof styles[number][0]
const notes = ['default', 'optional', 'TODO: revisit', 'in seconds', 'see the docs', 'required', 'do not edit', 'was 3', 'generated by the installer', 'keep in sync with CI', 'dev only']

// A comment of the document in another notation: the first character of the other sign stands in the place of the #
// and has its label, and the sign's other characters are added.
function inStyle(comment: Comment, style: CommentStyle): Edit[] {
  switch (style) {
    case '//': return [replaceOneForOne(comment.start, '/'), insertAt(comment.start + 1, '/')]
    case ';': return [replaceOneForOne(comment.start, ';')]
    case '--': return [replaceOneForOne(comment.start, '-'), insertAt(comment.start + 1, '-')]
    case '/* */': return [replaceOneForOne(comment.start, '/'), insertAt(comment.start + 1, '*'), insertAt(comment.end, ' */')]
    case '<!-- -->': return [replaceOneForOne(comment.start, '<'), insertAt(comment.start + 1, '!--'), insertAt(comment.end, ' -->')]
  }
}
// A new comment in another notation, e.g. `// default`.
const written = (style: CommentStyle, note: string) => style === '/* */' ? `/* ${note} */` : style === '<!-- -->' ? `<!-- ${note} -->` : `${style} ${note}`

function foreignComment(random: Random, scanned: Scan): Damage | undefined {
  const {comments, lineEnd} = scanned
  const style = random.weighted(styles)
  if (comments.length > 0 && random.chance(0.75)) {
    if (comments.length > 1 && random.chance(0.5)) return {edits: comments.flatMap(comment => inStyle(comment, style)), form: `${style} for every comment of the document`, wholeText: true}
    return {edits: inStyle(random.pick(comments), style), form: `${style} for one comment`}
  }
  const text = written(style, random.pick(notes))
  const atLineEnd = scanned.entries.filter(entry => lastOnLine(scanned, entry.value.end))
  if (atLineEnd.length > 0 && random.chance(0.55)) return {edits: [insertAt(random.pick(atLineEnd).value.end, `${random.chance(0.6) ? ' ' : '  '}${text}`)], form: `a new comment with ${style} after an entry`}
  if (scanned.entries.length === 0) return undefined
  const entry = random.pick(scanned.entries)
  return {edits: [insertAt(lineAt(scanned, entry.key.start).start, `${indentationAt(scanned, entry.key.start)}${text}${lineEnd}`)], form: `a new comment with ${style} on a line of its own`}
}

function commentWithoutHash(random: Random, scanned: Scan): Damage | undefined {
  const {codePoints, lineEnd} = scanned
  const outside = scanned.comments.filter(comment => comment.within === null && comment.end - comment.start > 2 && codePoints[comment.start + 1] !== '#')
  // What is left without the #: from the first code point after the # and the space after it.
  const restStart = (comment: Comment) => comment.start + (codePoints[comment.start + 1] === ' ' ? 2 : 1)
  // A comment that is an entry switched off, e.g. `# timeout = "5s"`, is a valid line without its #, and no mistake.
  const ownLine = outside.filter(comment => comment.ownLine && !runTableParser(`${codePoints.slice(restStart(comment), comment.end).join('')}\n`).valid)
  const afterValue = outside.filter(comment => !comment.ownLine)
  const withSpace = outside.map(comment => ({comment, spaces: Array.from({length: comment.end - comment.start}, (_, offset) => comment.start + offset).filter(position => position > comment.start + 2 && position < comment.end - 1 && codePoints[position] === ' ')}))
    .filter(({spaces}) => spaces.length > 0)
  const form = chooseForm(random, [
    ['a comment on a line of its own without its #', ownLine.length > 0 ? 40 : 0], ['a comment after a value without its #', afterValue.length > 0 ? 35 : 0], ['a comment that goes on in the next line', withSpace.length > 0 ? 25 : 0],
  ] as const)
  if (form === undefined) return undefined
  switch (form) {
    case 'a comment on a line of its own without its #': {
      const comment = random.pick(ownLine)
      return {edits: [removeRange(comment.start, restStart(comment))], form}
    }
    case 'a comment after a value without its #': {
      const comment = random.pick(afterValue)
      return {edits: [removeRange(comment.start, restStart(comment))], form}
    }
    case 'a comment that goes on in the next line': {
      const {comment, spaces} = random.pick(withSpace)
      return {edits: [{at: random.pick(spaces), remove: 1, insert: `${lineEnd}${indentationAt(scanned, comment.start)}`}], form}
    }
  }
}

export const commentKinds: KindDefinition[] = [
  {
    name: 'foreignComment', family: 'comments', weight: 3.5,
    description: 'A comment as another notation writes it: // ; -- /* */ <!-- -->',
    example: 'port = 8443 // default⏎; optional⏎workers = 32',
    variants: 'one comment of the document; every comment of the document; a new comment after an entry or on a line of its own',
    showable: 'yes on a line of its own and after a value: the sign starts nothing else there, and the comment ends at the line\'s end. With -- on a line of its own, the two characters read as a key by cells that valid TOML reads, and are shown so',
    apply: foreignComment,
  },
  {
    name: 'commentWithoutHash', family: 'comments', weight: 1,
    description: 'The text of a comment without its #: a note typed as it is, a comment that an editor switched on by mistake, or a long comment wrapped onto a second line',
    example: 'port = 8443 default⏎keep in sync with CI',
    variants: 'a comment on a line of its own; a comment after a value; a line end in the place of a space of a comment',
    showable: 'partly: after a complete value, text up to the line\'s end can be shown as a comment. On a line of its own the first word stands where a key stands and is shown as a key by cells that valid TOML reads, and the rest can be shown as a comment',
    apply: commentWithoutHash,
  },
]
