// What the generator of valid programs writes: 17 sorts of small programs, each a list of idioms. An idiom is one
// or more definitions as plain miniml text, as a person would write them, e.g. the length of a list by recursion.
// generate.ts draws idioms, gives their names other names, fills their holes and lays them out.
//
// The text of an idiom has three things that are not miniml:
// - `kind:` at its start says what the definitions give, e.g. `int:` for a number or a function that returns one.
//   Later definitions of the same program can then use them where a value of that kind fits.
// - `{a ~ b ~ c}` stands for one of the texts a, b and c, drawn anew for every program, e.g. `{0 ~ 1}`.
// - A name that starts with a capital letter is a hole, see `holes`. E.g. `Int` becomes an expression that gives a
//   number, written with the names that are in scope at the hole, and `Text` becomes a string.
// A comment before a definition belongs to the definition, and is written with it in some programs.
//
// Nothing checks names or types in miniml, so the idioms use names such as `head`, `tail` and `print_string` as if
// a library had them.

// What a value is, as far as the generator tells values apart: it decides which names fit into which hole.
export type Kind = 'int' | 'bool' | 'string' | 'list' | 'pair' | 'function' | 'unit' | 'any'

// The holes of an idiom, and what fills each:
// - Int, Bool, String, List, Pair, Unit, Function: an expression of that kind, of a few tokens.
// - Any: an expression of any of these kinds.
// - Number, Text, Flag: one integer, one string, `true` or `false`.
// - Numbers, Texts: a list of integers, a list of strings.
export const holes = ['Int', 'Bool', 'String', 'List', 'Pair', 'Unit', 'Function', 'Any', 'Number', 'Text', 'Flag', 'Numbers', 'Texts'] as const
export type Hole = typeof holes[number]

